#!/usr/bin/env tsx
/**
 * Reads the vendored OpenAPI spec (spec/betaseries-openapi.json) and emits
 * src/generated/operations.ts — a typed table of every BetaSeries operation,
 * grouped by category (OpenAPI tag). This is how the project stays in sync
 * with the real API surface without hand-writing 190+ parameter lists.
 *
 * Excluded from the generated output:
 *  - operations tagged "Authentication" (/oauth/device, /oauth/access_token)
 *  - /members/auth, /members/oauth, /members/access_token
 * Token acquisition is handled once, interactively, by `npm run auth`
 * (src/setup/auth-cli.ts) — never exposed as a runtime tool an LLM can call.
 *
 * Re-run after re-vendoring the spec: `npm run codegen`.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SPEC_PATH = resolve(__dirname, "../spec/betaseries-openapi.json");
const OUT_PATH = resolve(__dirname, "../src/generated/operations.ts");

const EXCLUDED_OPERATION_IDS = new Set([
  "post-members-auth",
  "post-members-oauth",
  "post-members-access-token",
]);
const EXCLUDED_TAGS = new Set(["Authentication"]);
const HTTP_METHODS = ["get", "post", "put", "delete", "patch"] as const;
type HttpMethod = (typeof HTTP_METHODS)[number];

interface ParamDef {
  name: string;
  description: string;
  required: boolean;
}

interface OperationDef {
  operationId: string;
  method: HttpMethod;
  path: string;
  summary: string;
  params: ParamDef[];
}

interface OpenApiSpec {
  paths: Record<
    string,
    Record<
      string,
      {
        operationId: string;
        summary?: string;
        tags?: string[];
        parameters?: Array<
          | { $ref: string }
          | {
              name: string;
              description?: string;
              required?: boolean;
              schema?: { type?: string };
            }
        >;
      }
    >
  >;
}

function main() {
  const spec: OpenApiSpec = JSON.parse(readFileSync(SPEC_PATH, "utf-8"));
  const categories = new Map<string, OperationDef[]>();

  let skipped = 0;
  let kept = 0;

  for (const [path, methods] of Object.entries(spec.paths)) {
    for (const [method, op] of Object.entries(methods)) {
      if (!HTTP_METHODS.includes(method as HttpMethod)) continue;
      const tags = op.tags ?? ["Uncategorized"];
      if (tags.some((t) => EXCLUDED_TAGS.has(t))) {
        skipped++;
        continue;
      }
      if (EXCLUDED_OPERATION_IDS.has(op.operationId)) {
        skipped++;
        continue;
      }

      const params: ParamDef[] = (op.parameters ?? [])
        .filter((p): p is Exclude<typeof p, { $ref: string }> => !("$ref" in p))
        .filter((p) => p.name !== "locale")
        .map((p) => ({
          name: p.name,
          description: (p.description ?? "").trim(),
          required: p.required ?? false,
        }));

      const operation: OperationDef = {
        operationId: op.operationId,
        method: method as HttpMethod,
        path,
        summary: (op.summary ?? "").trim(),
        params,
      };

      const category = (tags[0] ?? "uncategorized").toLowerCase();
      if (!categories.has(category)) categories.set(category, []);
      categories.get(category)!.push(operation);
      kept++;
    }
  }

  const sortedCategories = [...categories.entries()].sort(([a], [b]) => a.localeCompare(b));
  for (const [, ops] of sortedCategories) {
    ops.sort((a, b) => a.operationId.localeCompare(b.operationId));
  }

  const body = sortedCategories
    .map(([category, ops]) => `  ${JSON.stringify(category)}: ${JSON.stringify(ops, null, 2)},`)
    .join("\n");

  const output = `// AUTO-GENERATED by scripts/generate-tools.ts — do not edit by hand.
// Source: spec/betaseries-openapi.json (see spec/PROVENANCE.md for what was
// stripped from the upstream spec, and why).
// Regenerate with: npm run codegen

export type HttpMethod = "get" | "post" | "put" | "delete" | "patch";

export interface ParamDef {
  name: string;
  description: string;
  required: boolean;
}

export interface OperationDef {
  operationId: string;
  method: HttpMethod;
  path: string;
  summary: string;
  params: ParamDef[];
}

export const categories: Record<string, OperationDef[]> = {
${body}
};
`;

  mkdirSync(dirname(OUT_PATH), { recursive: true });
  writeFileSync(OUT_PATH, output);

  console.log(`Generated ${OUT_PATH}`);
  console.log(`  ${kept} operations kept, ${skipped} excluded (auth-related), across ${sortedCategories.length} categories`);
  for (const [category, ops] of sortedCategories) {
    console.log(`  - ${category}: ${ops.length}`);
  }
}

main();
